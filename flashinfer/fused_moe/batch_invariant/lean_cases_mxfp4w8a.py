"""Generate ``lean/BIKernels/MoEMxfp4w8aCases.lean`` from the Python side: the mixed MXFP4 x MXFP8 MoE classes' conformance
cases.

The file couples the Lean model (``lean/BIKernels/MoEMxfp4w8a.lean``) to :mod:`.spec_mxfp4w8a`: the GEMM1 chains of the class
(the bf16 classes' terms on the accumulators) and its GEMM2 conversion as kernel-``decide`` theorems and
``moemxfp4w8aconformance`` lines, and the grouped record space (``schedule_mxfp4w8a.grouped_knobs_mx``: one list for both
instruction classes) with its membership in both verified dense mixed spaces of ``Cases.lean`` and the tile-result
invariance over it on both classes, all decided by the kernel (no ``native_decide``: the file adds nothing to the axiom
policy). A regenerated file that differs from the committed one fails the device-free test
(``tests/batch_invariant/test_moe_mxfp4w8a_lean.py``), which needs no Lean toolchain.

    python -m flashinfer.fused_moe.batch_invariant.lean_cases_mxfp4w8a     # rewrite lean/BIKernels/MoEMxfp4w8aCases.lean
"""

from __future__ import annotations

import os
from typing import List, Tuple

from . import mterm as term
from .lean_cases import LEAN_DIR, lean_str
from .spec_mxfp4w8a import MoEMxfp4w8aSpec

CASES_PATH = os.path.join(LEAN_DIR, "BIKernels", "MoEMxfp4w8aCases.lean")


def space():
    """The grouped mixed space (the same records for both instruction classes), in enumeration order."""
    from .schedule_mxfp4w8a import grouped_knobs_mx

    ks = grouped_knobs_mx("mxfp4w8a")
    assert ks == grouped_knobs_mx("mxfp4w8a_k64"), (
        "one record list for both mixed classes"
    )
    return ks


def swap_space():
    """The swapped decode space's records in their Lean form (the stage width is a lowering choice, not a field of the
    record, so the two instruction classes' lists print as one), in enumeration order."""
    from .blocks.compile_mxfp4w8a import swapped_knobs_mx

    ks = [k.lean() for k in swapped_knobs_mx("mxfp4w8a")]
    assert ks == [k.lean() for k in swapped_knobs_mx("mxfp4w8a_k64")]
    return ks


def cases() -> List[Tuple[str, str, str]]:
    """``(name, python_sexpr, lean_term)``: the class's chain terms and the Lean expressions that must print identically."""
    alg = term.TermAlgebra()
    gl, ul = '(.leaf "g" [0, 0])', '(.leaf "u" [0, 0])'
    out = []
    s = MoEMxfp4w8aSpec(64, 32, 2, 8, alg=alg)
    out.append(
        ("gemm2", term.sexpr(s.gemm2()), 'MoEMxfp4w8a.gemm2T (.leaf "acc2" [0, 0])')
    )
    out.append(
        ("gemm1_swiglu", term.sexpr(s.gemm1()), f"MoEMxfp4w8a.gemm1T .silu {gl} {ul}")
    )
    s = MoEMxfp4w8aSpec(64, 32, 2, 8, alg=alg, act="gelu_tanh")
    out.append(
        (
            "gemm1_gelu_tanh",
            term.sexpr(s.gemm1()),
            f"MoEMxfp4w8a.gemm1T .geluTanh {gl} {ul}",
        )
    )
    s = MoEMxfp4w8aSpec(64, 32, 2, 8, alg=alg, act="relu2", gated=False)
    out.append(
        (
            "gemm1_relu2",
            term.sexpr(s.gemm1()),
            f"MoEMxfp4w8a.gemm1UngatedT .relu2 {ul}",
        )
    )
    s = MoEMxfp4w8aSpec(64, 32, 2, 8, alg=alg, act="identity", gated=False)
    out.append(
        (
            "gemm1_identity",
            term.sexpr(s.gemm1()),
            f"MoEMxfp4w8a.gemm1UngatedT .identity {ul}",
        )
    )
    return out


def render() -> str:
    """The content of ``MoEMxfp4w8aCases.lean``."""
    ks = space()
    L = [
        "import BIKernels.MoEMxfp4w8a",
        "import BIKernels.Cases",
        "namespace BIK",
        "-- GENERATED by flashinfer/fused_moe/batch_invariant/lean_cases_mxfp4w8a.py from the Python spec; do not edit.",
        "set_option maxRecDepth 8192",
        "",
        "/-! The mixed MXFP4-weight x MXFP8-activation MoE classes (`fused_moe/batch_invariant/spec_mxfp4w8a.py` vs "
        "`MoEMxfp4w8a.lean`): the GEMM1 chains (the bf16 classes' terms) and the GEMM2 conversion print identically "
        "(`mterm.sexpr` vs `MTerm.sexpr`); the grouped record space (one list for both instruction classes) satisfies the "
        "grouped predicate, is a member of both verified dense mixed spaces, and the tile result is invariant over it on both "
        "classes; the swapped decode space satisfies the swapped predicate, is a member of both dense mixed decode spaces, and "
        "the tile result is invariant over the union of the two spaces on both classes. Kernel `decide` throughout. -/",
    ]
    for name, sx, lt in cases():
        L.append(
            f"theorem moe_mxfp4w8a_{name} : ({lt}).sexpr = {lean_str(sx)} := by decide +kernel"
        )
    L.append(
        "def moeMxfp4w8aCases : List (String × MoE.MTerm) := ["
        + ", ".join(f'("{name}", {lt})' for name, _, lt in cases())
        + "]"
    )
    L.append(
        "def moeMxfp4w8aSpace : List GEMM.Config := ["
        + ", ".join(k.lean() for k in ks)
        + "]"
    )
    L.append(
        f"theorem moe_mxfp4w8a_space_size : moeMxfp4w8aSpace.length = {len(ks)} := by decide"
    )
    L.append(
        "theorem moe_mxfp4w8a_space_ok : moeMxfp4w8aSpace.all MoEMxfp4w8a.groupedOK = true := by decide +kernel"
    )
    L.append(
        "theorem moe_mxfp4w8a_space_in_mxw48 : moeMxfp4w8aSpace.all (fun c => gemmMxW48Space.any (fun s => s == c)) = true := by decide +kernel"
    )
    L.append(
        "theorem moe_mxfp4w8a_space_in_mxw48k64 : moeMxfp4w8aSpace.all (fun c => gemmMxW48K64Space.any (fun s => s == c)) = true := by decide +kernel"
    )
    L.append(
        "theorem moe_mxfp4w8a_space_invariant_k64 : ∀ c₁ ∈ moeMxfp4w8aSpace, ∀ c₂ ∈ moeMxfp4w8aSpace, ∀ (S₁ S₂ : Nat) (p q : GEMM.GTerm) "
        "(a : GEMM.RowData) (b : GEMM.ColData) (kb nblk : Nat), GEMM.tileResultMXW48K64 c₁ S₁ p a b kb nblk = GEMM.tileResultMXW48K64 c₂ S₂ q a b kb nblk := "
        "GEMM.space_invariantMXW48K64 moeMxfp4w8aSpace"
    )
    L.append(
        "theorem moe_mxfp4w8a_space_invariant_k32 : ∀ c₁ ∈ moeMxfp4w8aSpace, ∀ c₂ ∈ moeMxfp4w8aSpace, ∀ (S₁ S₂ : Nat) (p q : GEMM.GTerm) "
        "(a : GEMM.RowData) (b : GEMM.ColData) (kb nblk : Nat), GEMM.tileResultMXW48 c₁ S₁ p a b kb nblk = GEMM.tileResultMXW48 c₂ S₂ q a b kb nblk := "
        "GEMM.space_invariantMXW48 moeMxfp4w8aSpace"
    )
    sw = swap_space()
    L.append("def moeMxfp4w8aSwapSpace : List GEMM.Config := [" + ", ".join(sw) + "]")
    L.append(
        f"theorem moe_mxfp4w8a_swap_space_size : moeMxfp4w8aSwapSpace.length = {len(sw)} := by decide"
    )
    L.append(
        "theorem moe_mxfp4w8a_swap_space_ok : moeMxfp4w8aSwapSpace.all MoEMxfp4w8a.groupedSwapOK = true := by decide +kernel"
    )
    L.append(
        "theorem moe_mxfp4w8a_swap_space_in_mxw48_decode : moeMxfp4w8aSwapSpace.all (fun c => gemmMxW48SpaceDecode.any (fun s => s == c)) = true := by decide +kernel"
    )
    L.append(
        "theorem moe_mxfp4w8a_swap_space_in_mxw48k64_decode : moeMxfp4w8aSwapSpace.all (fun c => gemmMxW48K64SpaceDecode.any (fun s => s == c)) = true := by decide +kernel"
    )
    L.append(
        "theorem moe_mxfp4w8a_both_spaces_invariant_k64 : ∀ c₁ ∈ moeMxfp4w8aSpace ++ moeMxfp4w8aSwapSpace, ∀ c₂ ∈ moeMxfp4w8aSpace ++ moeMxfp4w8aSwapSpace, "
        "∀ (S₁ S₂ : Nat) (p q : GEMM.GTerm) (a : GEMM.RowData) (b : GEMM.ColData) (kb nblk : Nat), "
        "GEMM.tileResultMXW48K64 c₁ S₁ p a b kb nblk = GEMM.tileResultMXW48K64 c₂ S₂ q a b kb nblk := "
        "GEMM.space_invariantMXW48K64 (moeMxfp4w8aSpace ++ moeMxfp4w8aSwapSpace)"
    )
    L.append(
        "theorem moe_mxfp4w8a_both_spaces_invariant_k32 : ∀ c₁ ∈ moeMxfp4w8aSpace ++ moeMxfp4w8aSwapSpace, ∀ c₂ ∈ moeMxfp4w8aSpace ++ moeMxfp4w8aSwapSpace, "
        "∀ (S₁ S₂ : Nat) (p q : GEMM.GTerm) (a : GEMM.RowData) (b : GEMM.ColData) (kb nblk : Nat), "
        "GEMM.tileResultMXW48 c₁ S₁ p a b kb nblk = GEMM.tileResultMXW48 c₂ S₂ q a b kb nblk := "
        "GEMM.space_invariantMXW48 (moeMxfp4w8aSpace ++ moeMxfp4w8aSwapSpace)"
    )
    L.append("end BIK")
    return "\n".join(L) + "\n"


def summary() -> str:
    return f"moe mxfp4w8a lean_cases coverage: chains={len(cases())} space={len(space())} swap={len(swap_space())}"


def main(out_path: str = CASES_PATH) -> str:
    content = render()
    with open(out_path, "w") as f:
        f.write(content)
    s = summary()
    print(s)
    return s


if __name__ == "__main__":
    main()
