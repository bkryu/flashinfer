"""Generate ``lean/BIKernels/MoEMxfp8Cases.lean`` from the Python side: the MXFP8 MoE classes' conformance cases.

The file couples the Lean model (``lean/BIKernels/MoEMxfp8.lean``) to :mod:`.spec_mxfp8`: the GEMM1 chains of the class
(the bf16 classes' terms on the accumulators) and its GEMM2 conversion as kernel-``decide`` theorems and
``moemxfp8conformance`` lines, and the grouped record space (``schedule_mxfp8.grouped_knobs_mx``: one list for both
instruction classes) with its membership in both verified dense MX spaces of ``Cases.lean`` and the tile-result
invariance over it on both classes, all decided by the kernel (no ``native_decide``: the file adds nothing to the axiom
policy). A regenerated file that differs from the committed one fails the device-free test
(``tests/batch_invariant/test_moe_mxfp8_lean.py``), which needs no Lean toolchain.

    python -m flashinfer.fused_moe.batch_invariant.lean_cases_mxfp8     # rewrite lean/BIKernels/MoEMxfp8Cases.lean
"""

from __future__ import annotations

import os
from typing import List, Tuple

from . import mterm as term
from .lean_cases import LEAN_DIR, lean_str
from .spec_mxfp8 import MoEMxfp8Spec

CASES_PATH = os.path.join(LEAN_DIR, "BIKernels", "MoEMxfp8Cases.lean")


def space():
    """The grouped MX space (the same records for both instruction classes), in enumeration order."""
    from .schedule_mxfp8 import grouped_knobs_mx

    ks = grouped_knobs_mx("mxfp8")
    assert ks == grouped_knobs_mx("mxfp8_k64"), "one record list for both MX classes"
    return ks


def swapped_space():
    """The swapped record space (the swapped decode body's three token tiles), in enumeration order."""
    from .schedule_mxfp8 import swapped_knobs_mx

    return swapped_knobs_mx()


def cases() -> List[Tuple[str, str, str]]:
    """``(name, python_sexpr, lean_term)``: the class's chain terms and the Lean expressions that must print identically."""
    alg = term.TermAlgebra()
    gl, ul = '(.leaf "g" [0, 0])', '(.leaf "u" [0, 0])'
    out = []
    s = MoEMxfp8Spec(64, 32, 2, 8, alg=alg)
    out.append(
        ("gemm2", term.sexpr(s.gemm2()), 'MoEMxfp8.gemm2T (.leaf "acc2" [0, 0])')
    )
    out.append(
        ("gemm1_swiglu", term.sexpr(s.gemm1()), f"MoEMxfp8.gemm1T .silu {gl} {ul}")
    )
    s = MoEMxfp8Spec(64, 32, 2, 8, alg=alg, act="gelu_tanh")
    out.append(
        (
            "gemm1_gelu_tanh",
            term.sexpr(s.gemm1()),
            f"MoEMxfp8.gemm1T .geluTanh {gl} {ul}",
        )
    )
    s = MoEMxfp8Spec(64, 32, 2, 8, alg=alg, act="relu2", gated=False)
    out.append(
        ("gemm1_relu2", term.sexpr(s.gemm1()), f"MoEMxfp8.gemm1UngatedT .relu2 {ul}")
    )
    s = MoEMxfp8Spec(64, 32, 2, 8, alg=alg, act="identity", gated=False)
    out.append(
        (
            "gemm1_identity",
            term.sexpr(s.gemm1()),
            f"MoEMxfp8.gemm1UngatedT .identity {ul}",
        )
    )
    return out


def render() -> str:
    """The content of ``MoEMxfp8Cases.lean``."""
    ks = space()
    L = [
        "import BIKernels.MoEMxfp8",
        "import BIKernels.Cases",
        "namespace BIK",
        "-- GENERATED by flashinfer/fused_moe/batch_invariant/lean_cases_mxfp8.py from the Python spec; do not edit.",
        "set_option maxRecDepth 8192",
        "",
        "/-! The MXFP8 x MXFP8 MoE classes (`fused_moe/batch_invariant/spec_mxfp8.py` vs `MoEMxfp8.lean`): the GEMM1 chains "
        "(the bf16 classes' terms) and the GEMM2 conversion print identically (`mterm.sexpr` vs `MTerm.sexpr`); the grouped "
        "record space (one list for both instruction classes) satisfies the grouped predicate, is a member of both verified "
        "dense MX spaces, and the tile result is invariant over it on both classes. Kernel `decide` throughout. -/",
    ]
    for name, sx, lt in cases():
        L.append(
            f"theorem moe_mxfp8_{name} : ({lt}).sexpr = {lean_str(sx)} := by decide +kernel"
        )
    L.append(
        "def moeMxfp8Cases : List (String × MoE.MTerm) := ["
        + ", ".join(f'("{name}", {lt})' for name, _, lt in cases())
        + "]"
    )
    L.append(
        "def moeMxfp8Space : List GEMM.Config := ["
        + ", ".join(k.lean() for k in ks)
        + "]"
    )
    L.append(
        f"theorem moe_mxfp8_space_size : moeMxfp8Space.length = {len(ks)} := by decide"
    )
    L.append(
        "theorem moe_mxfp8_space_ok : moeMxfp8Space.all MoEMxfp8.groupedOK = true := by decide +kernel"
    )
    L.append(
        "theorem moe_mxfp8_space_in_mx8 : moeMxfp8Space.all (fun c => gemmMx8Space.any (fun s => s == c)) = true := by decide +kernel"
    )
    L.append(
        "theorem moe_mxfp8_space_in_mx8k64 : moeMxfp8Space.all (fun c => gemmMx8K64Space.any (fun s => s == c)) = true := by decide +kernel"
    )
    L.append(
        "theorem moe_mxfp8_space_invariant_k64 : ∀ c₁ ∈ moeMxfp8Space, ∀ c₂ ∈ moeMxfp8Space, ∀ (S₁ S₂ : Nat) (p q : GEMM.GTerm) "
        "(a : GEMM.RowData) (b : GEMM.ColData) (kb nblk : Nat), GEMM.tileResultMX8K64 c₁ S₁ p a b kb nblk = GEMM.tileResultMX8K64 c₂ S₂ q a b kb nblk := "
        "GEMM.space_invariantMX8K64 moeMxfp8Space"
    )
    L.append(
        "theorem moe_mxfp8_space_invariant_k32 : ∀ c₁ ∈ moeMxfp8Space, ∀ c₂ ∈ moeMxfp8Space, ∀ (S₁ S₂ : Nat) (p q : GEMM.GTerm) "
        "(a : GEMM.RowData) (b : GEMM.ColData) (kb nblk : Nat), GEMM.tileResultMX8 c₁ S₁ p a b kb nblk = GEMM.tileResultMX8 c₂ S₂ q a b kb nblk := "
        "GEMM.space_invariantMX8 moeMxfp8Space"
    )
    # the swapped record space (the swapped decode body, `blocks/swap_mxfp8.py`): the three token tiles, members of both dense MX
    # classes' predicates, disjoint from the grouped space; the union is one guarantee space on both classes
    sw = swapped_space()
    L.append(
        "def moeMxfp8SwapSpace : List GEMM.Config := ["
        + ", ".join(k.lean() for k in sw)
        + "]"
    )
    L.append(
        f"theorem moe_mxfp8_swap_space_size : moeMxfp8SwapSpace.length = {len(sw)} := by decide"
    )
    L.append(
        "theorem moe_mxfp8_swap_space_ok : moeMxfp8SwapSpace.all MoEMxfp8.groupedSwapOK = true := by decide +kernel"
    )
    L.append(
        "theorem moe_mxfp8_swap_space_not_grouped : moeMxfp8SwapSpace.all (fun c => !MoEMxfp8.groupedOK c) = true := by decide +kernel"
    )
    L.append(
        "theorem moe_mxfp8_both_spaces_invariant_k64 : ∀ c₁ ∈ moeMxfp8Space ++ moeMxfp8SwapSpace, ∀ c₂ ∈ moeMxfp8Space ++ moeMxfp8SwapSpace, "
        "∀ (S₁ S₂ : Nat) (p q : GEMM.GTerm) (a : GEMM.RowData) (b : GEMM.ColData) (kb nblk : Nat), "
        "GEMM.tileResultMX8K64 c₁ S₁ p a b kb nblk = GEMM.tileResultMX8K64 c₂ S₂ q a b kb nblk := "
        "GEMM.space_invariantMX8K64 (moeMxfp8Space ++ moeMxfp8SwapSpace)"
    )
    L.append(
        "theorem moe_mxfp8_both_spaces_invariant_k32 : ∀ c₁ ∈ moeMxfp8Space ++ moeMxfp8SwapSpace, ∀ c₂ ∈ moeMxfp8Space ++ moeMxfp8SwapSpace, "
        "∀ (S₁ S₂ : Nat) (p q : GEMM.GTerm) (a : GEMM.RowData) (b : GEMM.ColData) (kb nblk : Nat), "
        "GEMM.tileResultMX8 c₁ S₁ p a b kb nblk = GEMM.tileResultMX8 c₂ S₂ q a b kb nblk := "
        "GEMM.space_invariantMX8 (moeMxfp8Space ++ moeMxfp8SwapSpace)"
    )
    L.append("end BIK")
    return "\n".join(L) + "\n"


def summary() -> str:
    return f"moe mxfp8 lean_cases coverage: chains={len(cases())} space={len(space())} swapped={len(swapped_space())}"


def main(out_path: str = CASES_PATH) -> str:
    content = render()
    with open(out_path, "w") as f:
        f.write(content)
    s = summary()
    print(s)
    return s


if __name__ == "__main__":
    main()
