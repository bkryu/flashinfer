"""Generate ``lean/BIKernels/MoEMxfp4Cases.lean`` from the Python side: the MXFP4 MoE classes' conformance cases.

The file couples the Lean model (``lean/BIKernels/MoEMxfp4.lean``) to :mod:`.spec_mxfp4` node for node: per case a term
the Python spec builds (:mod:`.mterm` S-expression) and the Lean expression that must print identically. GEMM2's chain and
the GEMM1 chains of every gated and ungated activation with its parameter sets become theorems decided by ``decide
+kernel`` when their S-expression is at most :data:`.lean_cases.THEOREM_MAX_BYTES`; the larger chains are compared through
the ``moemxfp4conformance`` executable only (``tests/batch_invariant/test_moe_mxfp4_lean.py``).

    python -m flashinfer.fused_moe.batch_invariant.lean_cases_mxfp4     # rewrite lean/BIKernels/MoEMxfp4Cases.lean
"""

from __future__ import annotations

import os
from typing import List, Tuple

from . import mterm as term
from . import spec_mxfp4 as Q
from .lean_cases import (
    ACT_CASES,
    GLU_CASES,
    LEAN_DIR,
    THEOREM_MAX_BYTES,
    _UACT,
    lean_gact,
    lean_str,
)

CASES_PATH = os.path.join(LEAN_DIR, "BIKernels", "MoEMxfp4Cases.lean")
_G, _U = '(.leaf "g" [0, 0])', '(.leaf "u" [0, 0])'


def moe_mxfp4_cases() -> List[Tuple[str, str, str, bool]]:
    """``(name, python_sexpr, lean_term, as_theorem)``: the MXFP4 spec's terms and the Lean model's expressions that must
    print identically, built as the class builds them (:class:`.spec_mxfp4.MoEMxfp4Spec` on slot 0, column 0)."""
    alg = term.TermAlgebra()
    out: List[Tuple[str, str, str, bool]] = []

    def chain(name: str, t: term.Term, lean: str) -> None:
        sx = term.sexpr(t)
        out.append((name, sx, lean, len(sx) <= THEOREM_MAX_BYTES))

    s0 = Q.MoEMxfp4Spec(64, 32, 2, 8, alg=alg)
    chain("gemm2", s0.gemm2(), 'MoEMxfp4.mxOutT (.leaf "acc2" [0, 0])')
    # the gated GEMM1 chains of every activation and parameter set
    for name, act, params in GLU_CASES:
        s_ = Q.MoEMxfp4Spec(64, 32, 2, 8, alg=alg, act=act, params=params)
        assert s_.gated, (name, act)
        chain(
            f"gemm1_{name}",
            s_.gemm1(),
            f"MoEMxfp4.mxGluT {lean_gact(act, params)} {_G} {_U}",
        )
    # the ungated GEMM1 chains
    for name, act in (("act_relu2", "relu2"),) + tuple(ACT_CASES):
        s_ = Q.MoEMxfp4Spec(64, 32, 2, 8, alg=alg, act=act, gated=False)
        chain(f"gemm1_{name}", s_.gemm1(), f"MoEMxfp4.mxActT {_UACT[act]} {_U}")
    return out


def render() -> str:
    """The content of ``MoEMxfp4Cases.lean``."""
    L = [
        "import BIKernels.MoEMxfp4",
        "namespace BIK",
        "-- GENERATED by flashinfer/fused_moe/batch_invariant/lean_cases_mxfp4.py from the Python spec; do not edit.",
        "set_option maxRecDepth 8192",
        "",
        "/-! The MXFP4 MoE classes (`fused_moe/batch_invariant/spec_mxfp4.py` vs `MoEMxfp4.lean`): the GEMM1 chains of every "
        "gated and ungated activation on the raw accumulators and the GEMM2 chain print identically (`mterm.sexpr` vs "
        f"`MTerm.sexpr`). The chains up to {THEOREM_MAX_BYTES} bytes are kernel-`decide` theorems; every case is a "
        "`moemxfp4conformance` line. -/",
    ]
    mcs = moe_mxfp4_cases()
    for name, sx, lt, as_thm in mcs:
        if as_thm:
            L.append(
                f"theorem moe_mxfp4_{name} : ({lt}).sexpr = {lean_str(sx)} := by decide +kernel"
            )
    L.append(
        "def moeMxfp4Cases : List (String × MoE.MTerm) := ["
        + ", ".join(f'("{name}", {lt})' for name, _, lt, _ in mcs)
        + "]"
    )
    L.append("end BIK")
    return "\n".join(L) + "\n"


def summary() -> str:
    mcs = moe_mxfp4_cases()
    return (
        f"moe mxfp4 lean_cases coverage: cases={len(mcs)} theorems={sum(1 for c in mcs if c[3])} "
        f"conformance-only={sum(1 for c in mcs if not c[3])}"
    )


def main(out_path: str = CASES_PATH) -> str:
    content = render()
    with open(out_path, "w") as f:
        f.write(content)
    s = summary()
    print(s)
    return s


if __name__ == "__main__":
    main()
